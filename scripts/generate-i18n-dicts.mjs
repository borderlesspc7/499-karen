function escape(str) {
  return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

function buildDict(langIndex) {
  /** @type {Record<string, Record<string, string>>} */
  const dict = {}
  for (const [section, key, pt, en] of rows) {
    if (!dict[section]) dict[section] = {}
    dict[section][key] = langIndex === 0 ? pt : en
  }
  return dict
}

function emit(name, dict) {
  const lines = [`export const ${name} = {`]
  for (const [section, keys] of Object.entries(dict)) {
    lines.push(`  ${section}: {`)
    for (const [key, value] of Object.entries(keys)) {
      lines.push(`    ${key}: '${escape(value)}',`)
    }
    lines.push('  },')
  }
  lines.push('} as const')
  lines.push('')
  return lines.join('\n')
}

